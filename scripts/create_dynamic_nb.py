        "# Cell 6: Calibrated Sub-ppm Precursor Search & Normalized Logit Dot-Product Ranking\n",
        "def retrieve_candidates_for_molecule(mid, query_logit, precursor_mz, adduct, drift_ppm=1.5, primary_ppm=8.5, top_k=25):\n",
        "    neutral = estimate_neutral_mass(precursor_mz, adduct, drift_ppm=drift_ppm)\n",
        "    \n",
        "    if USE_V2_POOL and neutral is not None:\n",
        "        # 3-Tier Adaptive Window: 8.5 ppm -> 15.0 ppm -> 25.0 ppm\n",
        "        for ppm_tol in [primary_ppm, 15.0, 25.0]:\n",
        "            tol = neutral * (ppm_tol * 1e-6)\n",
        "            idx_l = np.searchsorted(POOL_MASSES, neutral - tol, side='left')\n",
        "            idx_r = np.searchsorted(POOL_MASSES, neutral + tol, side='right')\n",
        "            if (idx_r - idx_l) >= top_k:\n",
        "                break\n",
        "        \n",
        "        # If still fewer than top_k candidates, take the nearest 50 candidates in mass\n",
        "        if (idx_r - idx_l) < top_k:\n",
        "            center = np.searchsorted(POOL_MASSES, neutral)\n",
        "            idx_l = max(0, center - 25)\n",
        "            idx_r = min(len(POOL_MASSES), center + 25)\n",
        "        \n",
        "        if idx_r > idx_l:\n",
        "            cand_fps_packed = POOL_FP[idx_l:idx_r]\n",
        "            cand_fps = np.unpackbits(cand_fps_packed, axis=1).astype(np.float32)\n",
        "            cand_smi = POOL_SMILES[idx_l:idx_r]\n",
        "            cand_ik = POOL_IK14[idx_l:idx_r]\n",
        "            \n",
        "            # Normalized Logit Dot Product Ranking\n",
        "            bit_counts = cand_fps.sum(axis=1)\n",
        "            scores = (cand_fps @ query_logit) / np.sqrt(bit_counts + 5.0)\n",
        "            order = np.argsort(-scores)\n",
        "            \n",
        "            seen = set()\n",
        "            out = []\n",
        "            for idx in order:\n",
        "                k = cand_ik[idx]\n",
        "                if k in seen: continue\n",
        "                seen.add(k)\n",
        "                out.append(str(cand_smi[idx]))\n",
        "                if len(out) >= top_k: break\n",
        "            if len(out) > 0:\n",
        "                return out\n",
        "    \n",
        "    # Fallback retrieval using local candidate database\n",
        "    if neutral is not None and FALLBACK_MASSES is not None:\n",
        "        for ppm_tol in [primary_ppm, 15.0, 25.0]:\n",
        "            tol = neutral * (ppm_tol * 1e-6)\n",
        "            mask = np.abs(FALLBACK_MASSES - neutral) <= tol\n",
        "            if mask.sum() >= top_k:\n",
        "                break\n",
        "        \n",
        "        if mask.sum() >= top_k:\n",
        "            cand_indices = np.where(mask)[0]\n",
        "        else:\n",
        "            cand_indices = np.argsort(np.abs(FALLBACK_MASSES - neutral))[:50]\n",
        "        \n",
        "        sub_fps = FALLBACK_FPS[cand_indices].astype(np.float32)\n",
        "        bit_counts = sub_fps.sum(axis=1)\n",
        "        scores = (sub_fps @ query_logit) / np.sqrt(bit_counts + 5.0)\n",
        "        order = np.argsort(-scores)\n",
        "        \n",
        "        seen = set()\n",
