        "def bin_spectrum(mzs, intensities, n_bins=12000, bin_size=0.1):\n",
        "    out = np.zeros(n_bins, dtype=np.float32)\n",
        "    if mzs is None or intensities is None or len(mzs) == 0:\n",
        "        return out\n",
        "    mzs = np.asarray(mzs, dtype=np.float32)\n",
        "    intensities = np.asarray(intensities, dtype=np.float32)\n",
        "    n = min(len(mzs), len(intensities))\n",
        "    if n == 0: return out\n",
        "    mzs, intensities = mzs[:n], intensities[:n]\n",
        "    valid = np.isfinite(mzs) & np.isfinite(intensities) & (mzs >= 0) & (intensities > 0)\n",
        "    if not np.any(valid): return out\n",
        "    mzs, intensities = mzs[valid], intensities[valid]\n",
        "    intensities = np.sqrt(intensities)\n",
        "    idx = np.floor(mzs / bin_size).astype(np.int64)\n",
        "    valid_bins = (idx >= 0) & (idx < n_bins)\n",
        "    if not np.any(valid_bins): return out\n",
        "    np.add.at(out, idx[valid_bins], intensities[valid_bins])\n",
        "    m = np.max(out)\n",
        "    if m > 0: out /= m\n",
        "    return out\n",
